import { boolean, integer, jsonb, numeric, pgTable, serial, text, timestamp } from "drizzle-orm/pg-core";

/** One row per customer company. Company 1 is the bundled demonstration. */
export const companiesTable = pgTable("empresas", {
  id: serial("id").primaryKey(),
  name: text("nome").notNull(),
  /** ERP the company runs (sankhya, totvs, outro...). Only picks the starting template of the ficha; the real work is the implantation. */
  erp: text("erp").notNull().default("outro"),
  active: boolean("ativa").notNull().default(true),
  /**
   * True only when the company's own database and ficha are connected. Until then the assistant refuses to answer for it:
   * the shared connection holds the demonstration data, which must never be shown to another company.
   */
  dataReady: boolean("dados_prontos").notNull().default(false),
  /** Connection string of the company's own database, encrypted (AES-256-GCM). Never sent to a browser. Null for the demonstration company, which uses the shared connection. */
  dataUrlEnc: text("dados_url_cifrada"),
  /** The company's ficha de implantação (views, columns, code meanings), as JSON. */
  fichaJson: jsonb("ficha"),
  dataCheckedAt: timestamp("dados_verificados_em", { withTimezone: true }),
  /** Why the last verification failed, in plain words; null when it passed. */
  dataError: text("dados_erro"),
  /** Connection string of the customer's own ERP database (the source of the mirror), encrypted like dataUrlEnc. Read-only access. */
  sourceUrlEnc: text("origem_url_cifrada"),
  /** Kind of database at the source (postgres today; oracle and sqlserver when their readers exist). */
  sourceKind: text("origem_tipo").notNull().default("postgres"),
  /** Subjects (vendas, financeiro...) whose tables are copied from the source. */
  subjects: jsonb("assuntos").$type<string[]>().notNull().default([]),
  /** How often the scheduler loads, in minutes; null means only on demand. */
  loadEveryMin: integer("carga_intervalo_min"),
  /** What counts as a sale and as a receivable for this company (ERP-specific values; null means the ERP's usual defaults). */
  rules: jsonb("regras"),
  /** SHA-256 of the key the customer's side uses to send data (kind "recebida"); the key itself is shown once and never stored. */
  ingestKeyHash: text("ingestao_chave_hash"),
  /** First characters of that key, so a person can tell which one is in force. */
  ingestKeyPrefix: text("ingestao_chave_inicio"),
  ingestKeyAt: timestamp("ingestao_chave_em", { withTimezone: true }),
  /** The package of tables this company copies, when it was proposed for it (implantation agent) instead of taken from the ERP's ready-made one. */
  packageJson: jsonb("pacote"),
  /** The implantation agent's proposal while it is analysing, waiting for approval, or failed. */
  proposalJson: jsonb("proposta"),
  /** Monthly ceiling for the text-model cost of the company's answers, in US dollars. Null means no ceiling. */
  monthlyLimitUsd: numeric("limite_mensal_usd", { precision: 12, scale: 2 }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const usersTable = pgTable("usuarios", {
  id: serial("id").primaryKey(),
  /** Null for the product owner, who belongs to no company. */
  companyId: integer("empresa_id").references(() => companiesTable.id),
  email: text("email").notNull().unique(),
  name: text("nome").notNull(),
  /** dono (product owner) | administrador (company admin) | gestor (asks questions). */
  role: text("papel").notNull(),
  passwordHash: text("senha_hash").notNull(),
  /** True while the password was generated by an administrator and must be replaced at the first login. */
  mustChangePassword: boolean("senha_temporaria").notNull().default(true),
  active: boolean("ativo").notNull().default(true),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

/** Sessions are stored by the hash of their token, so a leaked table cannot be replayed. */
export const sessionsTable = pgTable("sessoes", {
  tokenHash: text("token_hash").primaryKey(),
  userId: integer("usuario_id").notNull().references(() => usersTable.id, { onDelete: "cascade" }),
  expiresAt: timestamp("expira_em", { withTimezone: true }).notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  /** Public identifier shown in "Meus aparelhos", so a session can be ended without ever sending its token hash to a browser. */
  id: serial("id").notNull().unique(),
  /** Last request that renewed the session (written at most once an hour; see auth.ts). */
  lastUsedAt: timestamp("ultimo_uso", { withTimezone: true }),
  /** Short label derived from the User-Agent ("iPhone · Safari"). No IP address is stored. */
  device: text("aparelho"),
  /** False when the person unticked "Manter conectado": the cookie ends with the browser and the session lasts 12 hours. */
  persistent: boolean("persistente").notNull().default(true),
});

/** One-time password reset links handed out by an administrator. Only the hash of the token is kept. */
export const passwordResetsTable = pgTable("redefinicoes_senha", {
  id: serial("id").primaryKey(),
  tokenHash: text("token_hash").notNull().unique(),
  userId: integer("usuario_id").notNull().references(() => usersTable.id, { onDelete: "cascade" }),
  /** Who generated the link (administrator or owner). */
  createdBy: integer("gerada_por").references(() => usersTable.id, { onDelete: "set null" }),
  expiresAt: timestamp("expira_em", { withTimezone: true }).notNull(),
  usedAt: timestamp("usada_em", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
